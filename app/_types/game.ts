  y: number;
  w: number;
  h: number;
  hp: number;
  maxHp: number;
  hue: number;
  alive: boolean;
  drop: ItemKind | null;
  kind: BrickKind;
  trait: BrickTrait;
  guardReady: boolean;
  healTimer: number;
  poisonTime: number;
  poisonTick: number;
  poisonSourcePaddleId: string | null;
  burnTime: number;
  burnTick: number;
  burnLevel: number;
  burnSourcePaddleId: string | null;
  healBlockTime: number;
  blastVulnerability: number;
  blastVulnerabilitySourcePaddleId: string | null;
  frostVulnerability: number;
  traitLockTime: number;
  lastHitPaddleId: string | null;
