import type { ClassSkillId, SkillCategory, SkillMechanic, UpgradeId } from "../skill-config";
import type { BalanceConfig, BotWaveSample, SkillBenchConfig } from "../balance-config";
import type { BenchmarkConfig } from "../benchmark-config";
import type { PARALLEL_BENCHMARK_RULESET, HeadlessTerminationReason, HeadlessTimeoutDiagnostic } from "../benchmark-headless";

export type PayloadId = "pierce" | "blast" | "glass" | "link";
export type ItemKind = "multiball" | "auto-barrier" | "core-repair" | "cooldown-reset";
export type BrickKind = "normal" | "boss-armor" | "boss-core" | "boss-minion";
export type BrickTrait = "standard" | "guard" | "explosive" | "indestructible" | "healer" | "reflector";
export type BossRewardId = UpgradeId;
export type BotPolicy = "balanced" | "survival" | "random";
export type BotSpeed = 1 | 2 | 4 | 8;
export type BenchmarkRunMode = "parallel" | "watch";
export type BotMetrics = { maxBalls: number; ballLosses: number; missileActivations: number; safetySaves: number; gravityRescues: number };
export type SkillBenchVariant = { batchId: string; environment: SkillBenchConfig["environment"]; skillId: UpgradeId | "original"; level: 0 | 1 | 2 | 3; skillValues: [number, number, number]; seed: number };
export type SkillSelectionSource = "start" | "wave" | "boss";
export type SkillSelectionEvent = { wave: number; skillId: UpgradeId; level: number; source: SkillSelectionSource };
export type SkillRunMetric = { activations: number; damage: number; kills: number };
export type BenchmarkRuleset = "live-v1" | "live-v2" | "watch-v1" | "parallel-v1" | typeof PARALLEL_BENCHMARK_RULESET;

export type BotRunResult = BotMetrics & {
  id: string;
  run: number;
  seed?: number;
  policy: BotPolicy;
  policyVersion?: string;
  engineVersion?: string;
  engineParity?: string;
  speed: BotSpeed;
  elapsed: number;
  wave: number;
  score: number;
  bricks: number;
  maxCombo: number;
  coreHp: number;
  upgrades: UpgradeId[];
  startingSkills: UpgradeId[];
  skillHistory: SkillSelectionEvent[];
  bossEnhancements?: Partial<Record<UpgradeId, number>>;
  skillMetrics: Partial<Record<UpgradeId, SkillRunMetric>>;
  createdAt: number;
  balanceConfig: BalanceConfig;
  benchmarkConfig: BenchmarkConfig | null;
  benchmarkRuleset?: BenchmarkRuleset | null;
  waveSamples: BotWaveSample[];
  evaluationComplete: boolean;
  terminationReason?: HeadlessTerminationReason;
  timeoutDiagnostic?: HeadlessTimeoutDiagnostic | null;
  skillBench: SkillBenchVariant | null;
};

export type Upgrade = {
  id: UpgradeId;
  name: string;
  category: SkillCategory;
  mechanic: SkillMechanic;
  tag: string;
  description: string;
  color: string;
};

export type UpgradeChoice = { upgrade: Upgrade; ballCost: 0 | 1 | 2 };

export type GhostRecord = {
  id: string;
  name: string;
  score: number;
  bricks: number;
  maxCombo: number;
  upgrades: UpgradeId[];
  skillHistory: SkillSelectionEvent[];
  skillMetrics: Partial<Record<UpgradeId, SkillRunMetric>>;
  paddleTrack: number[];
  createdAt: number;
};

